unsigned short crc8_unreflected_array( unsigned char* data, unsigned short len, unsigned char crc_in, const unsigned char* table )
{
	unsigned char crc8 = crc_in;

	while( len-- != 0 )
	{
		crc8 = table[ crc8 ^ *data++ ];
	}

	return crc8;
}

unsigned short crc8_unreflected_byte( unsigned char byte, unsigned char crc_in, const unsigned char* table )
{
	return table[ crc_in ^ byte ];
}



unsigned short crc16_unreflected_array( unsigned char* data, unsigned short len, unsigned short crc_in, const unsigned short* table )
{
	unsigned short crc16 = crc_in;

	while( len-- != 0 )
	{
		crc16 = table[ ((crc16 >> 8) ^ *data++) & 0xff ] ^ (crc16 << 8);
	}

	return crc16;
}

unsigned short crc16_unreflected_byte( unsigned char byte, unsigned short crc_in, const unsigned short* table )
{
	return table[ ((crc_in >> 8) ^ byte) & 0xff ] ^ (crc_in << 8);
}

unsigned short crc16_reflected_array( unsigned char* data, unsigned short len, unsigned short crc_in, const unsigned short* table )
{
	unsigned short crc16 = crc_in;

	while( len-- != 0 )
	{
		crc16 = table[(crc16 ^ *data++) & 0xff] ^ (crc16 >> 8);
	}

	return crc16;
}

unsigned short crc16_reflected_byte( unsigned char byte, unsigned short crc_in, const unsigned short* table )
{
	return table[(crc_in ^ byte) & 0xff] ^ (crc_in >> 8);;
}
